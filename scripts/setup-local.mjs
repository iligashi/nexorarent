// Creates the local env files for running the whole stack on one machine:
//   .env               -> MySQL container settings (read by docker compose)
//   server/.env        -> Express API (also loaded for the .NET API by `npm run dev:dotnet`)
//   client/.env.local  -> Next.js, routing /api/v1 to Express and the .NET API
//
// Passwords and JWT secrets are generated randomly. Existing files are never
// overwritten, so it is safe to run again.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const secret = (bytes) => randomBytes(bytes).toString('base64url');

const database = {
  port: '3307',
  name: 'drenas_rentacar',
  user: 'nexorarent',
  password: secret(24),
};

const files = {
  '.env': `# Local MySQL container (docker compose). Generated by npm run setup.
MYSQL_PORT=${database.port}
MYSQL_DATABASE=${database.name}
MYSQL_USER=${database.user}
MYSQL_PASSWORD=${database.password}
MYSQL_ROOT_PASSWORD=${secret(24)}
`,
  'server/.env': `# Local Express API. The .NET API reads this file too (npm run dev:dotnet).
# Generated by npm run setup.
NODE_ENV=development
PORT=4000
DB_HOST=127.0.0.1
DB_PORT=${database.port}
DB_NAME=${database.name}
DB_USER=${database.user}
DB_PASSWORD=${database.password}
JWT_SECRET=${secret(48)}
JWT_REFRESH_SECRET=${secret(48)}
CLIENT_URL=http://localhost:3000
COOKIE_SAME_SITE=lax
`,
  'client/.env.local': `# Local Next.js. The browser calls /api/v1 on this site and Next.js forwards
# each route to Express or the .NET API (see next.config.ts).
NEXT_PUBLIC_API_URL=/api/v1
NEXT_PUBLIC_SITE_URL=http://localhost:3000
EXPRESS_API_URL=http://localhost:4000
DOTNET_API_URL=http://localhost:5080
`,
};

for (const [relativePath, content] of Object.entries(files)) {
  const fullPath = path.join(root, relativePath);
  if (existsSync(fullPath)) {
    console.log(`kept     ${relativePath} (already exists)`);
    continue;
  }
  writeFileSync(fullPath, content, { flag: 'wx' });
  console.log(`created  ${relativePath}`);
}

console.log(`
Next steps:
  npm run db:up      start MySQL 8.4 in Docker
  npm run db:reset   create tables and sample data
  npm run dev:all    start Next.js, Express and the .NET API`);
